    function ecOpenLegalModal(type, e) {
        if (e) e.preventDefault();
        const modal = document.getElementById('ec-legal-modal');
        if (!modal) return;
        ecSwitchLegalTab(type);
        modal.classList.add('active');
        modal.setAttribute('aria-hidden', 'false');
        document.body.style.overflow = 'hidden';
    }

    function ecCloseLegalModal() {
        const modal = document.getElementById('ec-legal-modal');
        if (!modal) return;
        modal.classList.remove('active');
        modal.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = '';
    }

    function ecSwitchLegalTab(type) {
        const data = ecLegalData[type] || ecLegalData.privacy;
        document.getElementById('ec-legal-title').innerText = data.title;
        document.getElementById('ec-legal-modal-body').innerHTML = data.html;

        document.querySelectorAll('.ec-legal-tab-btn').forEach(btn => {
            if (btn.getAttribute('data-target') === type) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
        document.getElementById('ec-legal-modal-body').scrollTop = 0;
    }

    document.addEventListener('DOMContentLoaded', function() {
        document.querySelectorAll('.ec-legal-link').forEach(link => {
            link.addEventListener('click', function(e) {
                const type = this.getAttribute('data-legal');
                ecOpenLegalModal(type, e);
            });
        });

        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape') {
                ecCloseLegalModal();
            }
        });
    });
